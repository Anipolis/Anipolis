-- ============================================================
-- 173_posts_content_no_control_chars: 投稿本文に表示されない制御文字を入れさせない（#245）
-- ============================================================
-- 投稿本文は長さと空かどうかだけを見ていたので、制御文字（例: U+0017）だけの投稿が「本文あり」として
-- 保存できた。見た目はほぼ空なのに長い投稿として扱われ、「もっと見る」の判定や読み上げソフト向けの
-- 情報を大きく膨らませた。
--
-- 本文に残してよい制御文字は、タブ（U+0009）・改行（LF U+000A・CR U+000D）だけにする。
-- それ以外の C0（U+0001〜U+001F）・DEL（U+007F）・C1（U+0080〜U+009F）を含む本文は CHECK で拒否する
-- （NUL は PostgreSQL の text に入らない）。アプリは保存の前に同じ範囲を取り除く
-- （normalizePostContent、src/lib/post-content.ts）。絵文字の結合（ZWJ）・異体字セレクタ・結合文字は対象外。
--
-- 本番の既存データ: 38 件のうち 2 件が対象（2026-10-21 確認。どちらも 2026-05-18 の再現確認の投稿で、
-- 中身は制御文字と改行だけ）。既存の行は消さずに残すため NOT VALID で足す。新しい投稿と、本文を
-- 書き換える更新は検査する。2 件を片付けたら VALIDATE CONSTRAINT で全体を検査済みにできる。

ALTER TABLE public.posts
    ADD CONSTRAINT posts_content_no_control_chars
    CHECK (content !~ '[\x01-\x08\x0B\x0C\x0E-\x1F\x7F\u0080-\u009F]')
    NOT VALID;
